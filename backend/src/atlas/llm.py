"""LLM providers behind a domain-neutral interface. Domain code never imports a model SDK directly.
Supports:
- Real local/cloud LLMs via Ollama (`ollama:gemma4:12b`, `ollama:gemma4:31b-cloud`) wrapped in Deep Agents (`create_deep_agent`)
  or direct ChatOllama invocation.
- Any LangChain model string (`openai:...`, `anthropic:...`).
- `template` deterministic fallback when explicitly requested for fast unit tests."""
from __future__ import annotations

import logging
import time
from dataclasses import dataclass, field
from typing import Any, Protocol

from atlas.config import get_settings
from atlas.telemetry import span

log = logging.getLogger("atlas.llm")


@dataclass
class LLMResult:
    text: str
    provider: str
    usage: dict[str, Any] = field(default_factory=dict)
    limitations: list[str] = field(default_factory=list)


class LLMProvider(Protocol):
    name: str

    def generate(self, system: str, prompt: str, fallback_text: str) -> LLMResult: ...


class TemplateProvider:
    """Deterministic fallback, no model call. Labeled as such everywhere."""
    name = "template(no-llm)"

    def generate(self, system: str, prompt: str, fallback_text: str) -> LLMResult:
        return LLMResult(
            text=fallback_text,
            provider=self.name,
            usage={"input_tokens": 0, "output_tokens": 0, "total_tokens": 0, "latency_ms": 0},
            limitations=["Generated by deterministic template; no language model was used."],
        )


def _resolve_model(model_spec: Any) -> tuple[Any, str]:
    if isinstance(model_spec, str) and model_spec.startswith("ollama:"):
        from langchain_ollama import ChatOllama
        ollama_name = model_spec.removeprefix("ollama:")
        return ChatOllama(model=ollama_name, temperature=0.2, num_predict=700), f"ollama:{ollama_name}"
    if isinstance(model_spec, str):
        return model_spec, model_spec
    return model_spec, type(model_spec).__name__


class DeepAgentsProvider:
    """Runs a Deep Agents harness (LangGraph under the hood) over a real LLM (e.g., Ollama gemma4:12b)."""

    def __init__(self, model: Any, max_retries: int = 1, use_harness: bool = True):
        self.raw_model = model
        self.max_retries = max_retries
        self.use_harness = use_harness
        _, label = _resolve_model(model)
        self.name = f"deepagents({label})" if use_harness else f"llm({label})"

    def generate(self, system: str, prompt: str, fallback_text: str) -> LLMResult:
        from deepagents import create_deep_agent
        last_err: Exception | None = None
        for attempt in range(self.max_retries + 1):
            t0 = time.perf_counter()
            try:
                model_obj, _ = _resolve_model(self.raw_model)
                with span("llm.deepagents", provider=self.name, attempt=attempt):
                    if self.use_harness and not hasattr(self.raw_model, "_is_mock_broken"):
                        agent = create_deep_agent(model=model_obj, tools=[], system_prompt=system)
                        res = agent.invoke(
                            {"messages": [{"role": "user", "content": prompt}]},
                            config={"recursion_limit": 8},
                        )
                        msg = res["messages"][-1]
                    else:
                        msg = model_obj.invoke([("system", system), ("user", prompt)])
                latency_ms = int((time.perf_counter() - t0) * 1000)
                text = msg.content if isinstance(msg.content, str) else str(msg.content)
                usage = dict(getattr(msg, "usage_metadata", None) or {})
                usage["latency_ms"] = latency_ms
                return LLMResult(text=text.strip(), provider=self.name, usage=usage, limitations=[])
            except Exception as e:  # provider errors -> retry, then fallback
                last_err = e
                log.warning("provider %s failed attempt %s: %s", self.name, attempt, type(e).__name__)
        fb = TemplateProvider().generate(system, prompt, fallback_text)
        fb.limitations.append(f"Provider {self.name} failed ({type(last_err).__name__}); fell back to template.")
        fb.provider = f"{self.name}->fallback:template"
        return fb


_override: LLMProvider | None = None


def set_provider(p: LLMProvider | None) -> None:
    global _override
    _override = p


def get_provider() -> LLMProvider:
    if _override is not None:
        return _override
    m = get_settings().llm_model
    return TemplateProvider() if m == "template" else DeepAgentsProvider(m)
